def crime_name(doc_title: str, article: str) -> str:
    return CRIME_NAMES.get(article, "") if doc_title == CRIMINAL_LAW_TITLE else ""


def expand_query(query: str) -> str:
    extra = [terms for pat, terms in GLOSSARY if re.search(pat, query, re.I)]
    return f"{query}（相关概念：{'；'.join(extra)}）" if extra else query


